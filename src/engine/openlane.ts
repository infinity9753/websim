// Export a design as an OpenLane 2 / LibreLane project (#59): config.json, the RTL sources, an SDC and a README, so
// the design can be taken through a real open-source flow on the sky130 PDK. WebSim does not run that flow.

export interface OpenLaneOptions {
  top: string;
  /** RTL sources: project path -> text. */
  files: Record<string, string>;
  clockPort?: string;
  /** Clock period, ns. */
  period: number;
  /** Constraint text to use instead of the generated one. */
  sdc?: string;
  /** Core utilization, percent. */
  util: number;
  /** Input ports (for the generated SDC). */
  inputs: string[];
}

/** The input port most often used as an edge in the sources (a name like clk wins a tie). */
export function guessClock(files: Record<string, string>, inputs: string[]): string | undefined {
  const text = Object.values(files).join('\n').replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
  let best: string | undefined, score = 0;
  for (const p of inputs) {
    const n = (text.match(new RegExp(`\\b(?:pos|neg)edge\\s+${p.replace(/\W/g, '\\$&')}\\b`, 'g')) ?? []).length;
    const s = n * 2 + (n && /^(clk|clock|.*_clk|clk_.*)$/i.test(p) ? 1 : 0);
    if (s > score) { score = s; best = p; }
  }
  return best;
}

/** Constraints for a single-clock design: 20% of the period as input and output delay, a sky130 HD load. */
export function defaultSdc(o: { clockPort?: string; period: number; inputs: string[] }): string {
  const io = (o.period * 0.2).toFixed(3);
  const clk = o.clockPort;
  const ins = o.inputs.filter(p => p !== clk);
  return [
    `# Generated by WebSim for OpenLane 2 / LibreLane (edit to match the real environment of the design)`,
    clk ? `create_clock -name ${clk} -period ${o.period} [get_ports ${clk}]` : `create_clock -name virtual_clk -period ${o.period}`,
    `set_clock_uncertainty 0.25`,
    ...(ins.length ? [`set_input_delay -clock ${clk ?? 'virtual_clk'} ${io} [get_ports {${ins.join(' ')}}]`] : []),
    `set_output_delay -clock ${clk ?? 'virtual_clk'} ${io} [all_outputs]`,
    `set_load 0.0334 [all_outputs]`,
    `set_input_transition 0.1 [all_inputs]`,
    '',
  ].join('\n');
}

/** Files of the project, rooted at "<top>/". */
export function openlaneProject(o: OpenLaneOptions): Record<string, string> {
  const root = `${o.top}/`;
  const srcs = Object.keys(o.files).map(f => `src/${f.replace(/^.*\//, '')}`);
  const config: Record<string, unknown> = {
    meta: { version: 2 },
    DESIGN_NAME: o.top,
    VERILOG_FILES: srcs.map(s => `dir::${s}`),
    ...(o.clockPort ? { CLOCK_PORT: o.clockPort } : { CLOCK_PORT: null }),
    CLOCK_PERIOD: o.period,
    PNR_SDC_FILE: `dir::${o.top}.sdc`,
    SIGNOFF_SDC_FILE: `dir::${o.top}.sdc`,
    FP_CORE_UTIL: o.util,
  };
  const out: Record<string, string> = {};
  out[`${root}config.json`] = JSON.stringify(config, null, 2) + '\n';
  Object.entries(o.files).forEach(([f, t], i) => { out[`${root}${srcs[i]}`] = t; });
  out[`${root}${o.top}.sdc`] = o.sdc ?? defaultSdc(o);
  out[`${root}README.md`] = readme(o, srcs);
  return out;
}

function readme(o: OpenLaneOptions, srcs: string[]): string {
  return `# ${o.top} — OpenLane 2 / LibreLane project (exported by WebSim)

This folder takes \`${o.top}\` through a real open-source RTL-to-GDSII flow (Yosys, OpenROAD, Magic, KLayout, Netgen)
on the SkyWater sky130 PDK (default standard cells \`sky130_fd_sc_hd\`). WebSim's own ASIC flow uses an invented
educational library; this export is the bridge to a manufacturable layout.

| File | |
|---|---|
| \`config.json\` | flow configuration: design name, sources, clock ${o.clockPort ? `\`${o.clockPort}\`` : '(none: combinational, virtual clock in the SDC)'}, period ${o.period} ns, core utilization ${o.util}% |
${srcs.map(s => `| \`${s}\` | RTL source |`).join('\n')}
| \`${o.top}.sdc\` | timing constraints${o.sdc ? ' (from the WebSim project)' : ' (generated: check the input / output delays)'} |

## Run

With Nix (recommended by the LibreLane documentation) or the Docker image:

\`\`\`sh
# LibreLane (successor of OpenLane 2)
librelane config.json
# or OpenLane 2
openlane config.json
# OpenLane 2 in its container
openlane --dockerized config.json
\`\`\`

The results land in \`runs/<tag>/\`: the final GDSII, DEF, the gate-level netlist, SPEF and the timing reports of
OpenSTA (\`runs/<tag>/final/\`); open the GDSII with KLayout.

## Before tape-out

- The period, the IO delays and the load in \`${o.top}.sdc\` are estimates; set them from the environment of the chip.
- Behavioural memories become flip-flops; large memories need SRAM macros.
- Run the flow's DRC / LVS / antenna checks and look at the timing reports of all corners.
`;
}
