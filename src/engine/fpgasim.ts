// Simulation models for gate-level netlists of the FPGA synthesis targets (#52): the primitive models that ship with
// Yosys (cells_sim.v, read from the installed package by vite.config.ts), plus behavioural models of the DSP multipliers
// that Yosys only has as blackboxes, for the combinational multiply mode its DSP mapping uses.
import YOSYS from 'virtual:yosys-sim';
import type { SynthTarget } from './synth';

export const FPGA_SIM_TARGETS: SynthTarget[] = ['ice40', 'ecp5', 'gowin', 'xilinx'];

/** `include "x" lines replaced by the file from the same Yosys directory. */
function inline(dir: string, text: string, depth = 0): string {
  if (depth > 8) throw new Error('include nesting too deep');
  return text.replace(/^[ \t]*`include\s+"([^"]+)".*$/gm, (_, f: string) => {
    const inc = YOSYS[`${dir}/${f}`];
    if (inc === undefined) throw new Error(`Yosys model file ${dir}/${f} is missing`);
    return inline(dir, inc, depth + 1);
  });
}

/** A module declaration from a Yosys blackbox file, with `body` inserted before endmodule. */
function withBody(dir: string, file: string, name: string, body: string): string {
  const src = YOSYS[`${dir}/${file}`] ?? '';
  const m = new RegExp(`module\\s+${name}\\s*\\([\\s\\S]*?\\nendmodule`).exec(src);
  if (!m) throw new Error(`no ${name} declaration in Yosys ${dir}/${file}`);
  return m[0].replace(/endmodule$/, `${body}\nendmodule`);
}

const bits = (p: string, n: number) => Array.from({ length: n }, (_, i) => `${p}${n - 1 - i}`).join(', ');

/** ECP5 MULT18X18D as mapped by Yosys: A x B with SIGNEDA / SIGNEDB, no registers. */
function ecp5Dsp(): string {
  return withBody('ecp5', 'cells_bb.v', 'MULT18X18D', `
  // WebSim behavioural model (combinational multiply; the registered modes are not modelled)
  generate if (REG_INPUTA_CLK != "NONE" || REG_INPUTB_CLK != "NONE" || REG_INPUTC_CLK != "NONE" || REG_PIPELINE_CLK != "NONE" || REG_OUTPUT_CLK != "NONE")
    $error("WebSim: registered MULT18X18D modes have no simulation model");
  endgenerate
  wire [17:0] ws_a = {${bits('A', 18)}}, ws_b = {${bits('B', 18)}};
  wire [35:0] ws_p = {{18{SIGNEDA & ws_a[17]}}, ws_a} * {{18{SIGNEDB & ws_b[17]}}, ws_b};
  assign {${bits('P', 36)}} = ws_p;
  assign SIGNEDP = (SIGNEDA & ws_a[17]) ^ (SIGNEDB & ws_b[17]);`);
}

/** Gowin MULT9X9 / MULT18X18 / MULT36X36 as mapped by Yosys: A x B with ASIGN / BSIGN, no registers. */
function gowinDsp(name: string, w: number, shift: boolean): string {
  const regs = w === 36 ? 'AREG || BREG || OUT0_REG || OUT1_REG || PIPE_REG || ASIGN_REG || BSIGN_REG' : 'AREG || BREG || OUT_REG || PIPE_REG || ASIGN_REG || BSIGN_REG || SOA_REG';
  return withBody('gowin', 'cells_xtra_gw1n.v', name, `
  // WebSim behavioural model (combinational multiply; the registered modes are not modelled)
  generate if (${regs})
    $error("WebSim: registered ${name} modes have no simulation model");
  endgenerate
  wire [${w - 1}:0] ws_a = ${shift ? 'ASEL ? SIA : A' : 'A'}, ws_b = ${shift ? 'BSEL ? SIB : B' : 'B'};
  assign DOUT = {{${w}{ASIGN & ws_a[${w - 1}]}}, ws_a} * {{${w}{BSIGN & ws_b[${w - 1}]}}, ws_b};${shift ? `
  assign SOA = ws_a;
  assign SOB = ws_b;` : ''}`);
}

/** One self-contained Verilog file with the primitive models of an FPGA target. */
export function fpgaSimModels(target: SynthTarget): string {
  const head = `// Simulation models of ${target} primitives for gate-level simulation (generated by WebSim).
// From Yosys (https://github.com/YosysHQ/yosys, ISC license), share/${target === 'ecp5' ? 'ecp5' : target}/cells_sim.v;
// the specify delays are picoseconds.
\`timescale 1ps/1ps
`;
  switch (target) {
    case 'ice40': return head + inline('ice40', YOSYS['ice40/cells_sim.v']);
    case 'ecp5': return head + inline('ecp5', YOSYS['ecp5/cells_sim.v']) + '\n' + ecp5Dsp() + '\n';
    case 'gowin': return head + inline('gowin', YOSYS['gowin/cells_sim.v']) + '\n' + [gowinDsp('MULT9X9', 9, true), gowinDsp('MULT18X18', 18, true), gowinDsp('MULT36X36', 36, false)].join('\n') + '\n';
    case 'xilinx': return head + inline('xilinx', YOSYS['xilinx/cells_sim.v']);
    default: throw new Error(`no simulation models for target ${target}`);
  }
}
